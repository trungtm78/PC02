#!/usr/bin/env node
/**
 * Generate `src/feature-flags/feature-registry.generated.ts` from every
 * `src/**\/feature.manifest.ts`.
 *
 * Why this exists: the registry was a hand-maintained import list, and adding
 * a module meant remembering to edit it. Three times somebody did not —
 * `comprehensive` (v0.37.2.1), `document-templates` (v0.69.0.1), and
 * `edit-window-requests`, which is still only reachable by typing its URL.
 * Each time the symptom was the same: the frontend advertises a menu entry
 * whose flag the backend has never heard of, so the item silently vanishes.
 *
 * The existing spec compared only the *count* of manifests, which cannot
 * catch a module that was never added in the first place.
 *
 * Mirrors `scripts/generate-shared-enums.cjs`: same shape, same commit-the-
 * output convention, wired into `npm run build` beside `gen:enums`.
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(SRC, 'feature-flags', 'feature-registry.generated.ts');

/** Every `feature.manifest.ts` under src/, sorted for a stable diff. */
function findManifests(dir, found = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === 'dist') continue;
      findManifests(full, found);
    } else if (entry.name === 'feature.manifest.ts') {
      found.push(full);
    }
  }
  return found.sort();
}

/**
 * The exported const's name, e.g. `CASES_MANIFEST`.
 *
 * Read from the file rather than derived from the folder, because the two do
 * not always agree (`reports/tdac` exports `TDAC_MANIFEST`).
 */
function exportedName(file) {
  const source = fs.readFileSync(file, 'utf8');
  const match = source.match(
    /export\s+const\s+([A-Za-z0-9_]+)\s*:\s*FeatureManifest/,
  );
  if (!match) {
    throw new Error(
      `${path.relative(SRC, file)}: no "export const X: FeatureManifest" found. ` +
        `The generator matches on that shape; rename the export or widen the regex.`,
    );
  }
  return match[1];
}

function relImport(file) {
  const from = path.join(SRC, 'feature-flags');
  let rel = path.relative(from, file).replace(/\\/g, '/');
  if (!rel.startsWith('.')) rel = './' + rel;
  return rel.replace(/\.ts$/, '');
}

function main() {
  const files = findManifests(SRC);
  const entries = files.map((file) => ({
    name: exportedName(file),
    from: relImport(file),
  }));

  const dupes = entries
    .map((e) => e.name)
    .filter((name, i, all) => all.indexOf(name) !== i);
  if (dupes.length > 0) {
    throw new Error(
      `Duplicate manifest export names: ${[...new Set(dupes)].join(', ')}. ` +
        `Each manifest needs a unique const name.`,
    );
  }

  const lines = [
    '// AUTO-GENERATED by scripts/generate-feature-registry.cjs — do not edit.',
    '// Run `npm run gen:feature-registry` (or `npm run build`) to refresh.',
    '//',
    '// Source of truth is every src/**/feature.manifest.ts. The list used to be',
    '// maintained by hand, and three modules shipped without being added to it.',
    '',
    "import type { FeatureManifest } from './feature-manifest';",
    ...entries.map((e) => `import { ${e.name} } from '${e.from}';`),
    '',
    'export const GENERATED_FEATURE_REGISTRY: readonly FeatureManifest[] = [',
    ...entries.map((e) => `  ${e.name},`),
    '] as const;',
    '',
  ];

  fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
  process.stdout.write(
    `feature-registry.generated.ts: ${entries.length} manifest(s)\n`,
  );
}

main();
