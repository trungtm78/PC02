/** The one-line message for a refused `/authz` request: by the server's code when known, else what the server said. */
export function permissionErrorText(code: string | undefined, serverMessage: string): string {
  if (code && Object.prototype.hasOwnProperty.call(permissions.errors, code)) return permissions.errors[code];
  return serverMessage && serverMessage !== code ? serverMessage : permissions.common.unknownError;
}
