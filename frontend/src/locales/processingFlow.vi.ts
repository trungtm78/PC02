/**
 * The sentence for a refused request: by the server's code when known, else what the server said, else a general one.
 * A code this screen does not know is never shown raw.
 */
export function errorText(code: string | undefined, serverMessage?: string): string {
  const known = processingFlow.errors;
  if (code && Object.prototype.hasOwnProperty.call(known, code)) return known[code];
  return serverMessage && serverMessage !== code ? serverMessage : processingFlow.errorFallback;
}
